import assert from 'node:assert/strict';
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import * as XLSX from 'xlsx';
import { jsPDF } from 'jspdf';
import autoTable from 'jspdf-autotable';
const root = fileURLToPath(new URL('../', import.meta.url));
const rows = Array.from({ length: 80 }, (_, index) => ({ Name: `QA User ${index + 1}`, Program: 'Citizenship of Argentina', Category: 'Citizenship', Domain: 'dreamcountryvisas.in' }));
const sheet = XLSX.utils.json_to_sheet(rows);
const book = XLSX.utils.book_new();
XLSX.utils.book_append_sheet(book, sheet, 'Submissions');
const bytes = XLSX.write(book, { type: 'buffer', bookType: 'xlsx' });
const restored = XLSX.read(bytes, { type: 'buffer' });
assert.deepEqual(XLSX.utils.sheet_to_json(restored.Sheets.Submissions), rows);
const pdf = new jsPDF({ orientation: 'landscape', unit: 'pt' });
autoTable(pdf, { head: [Object.keys(rows[0])], body: rows.map(Object.values) });
assert(Buffer.from(pdf.output('arraybuffer')).subarray(0, 5).equals(Buffer.from('%PDF-')));
assert(pdf.internal.getNumberOfPages() > 1);
const result = { checks: 2, failures: [], xlsxRowsRoundTripped: rows.length, pdfPages: pdf.internal.getNumberOfPages(), browserDownloadNotTested: true };
fs.writeFileSync(path.join(root, 'export-qa.json'), JSON.stringify(result, null, 2));
console.log(JSON.stringify(result, null, 2));
